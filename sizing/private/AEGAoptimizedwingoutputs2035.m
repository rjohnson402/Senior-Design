function s=AEGAoptimizedwingoutputs2035(s)
% Expose the selected complete aircraft and verify selection/geometry/closure.
profiles=unique(s.best.Profile,'stable');
s.optimization_variables=struct('fixed',["W/S" "AR" "taper"], ...
    'adaptive',["W/S" "taper"], ...
    'adaptive_full_extension_AR',s.options.extended_AR, ...
    'deployment','Minimum cruise power within clean-lift and packing limits');
if strcmp(s.options.retraction_policy,'manual')
    s.optimization_variables.adaptive(end+1)="retraction capability";
end
s.optimized_aircraft=repmat(struct('profile',"",'fixed',[],'adaptive',[]),numel(profiles),1);
geometry=struct([]); masses=struct([]); checks=struct([]);
for ip=1:numel(profiles)
    s.optimized_aircraft(ip).profile=profiles(ip);
end
for j=1:height(s.best)
    b=s.best(j,:); if ~b.PassesScreen, continue; end
    a=s.best_details{j}; ip=find(profiles==b.Profile,1);
    family=lower(char(b.Family)); s.optimized_aircraft(ip).(family)=a;
    candidates=s.evaluated_designs(s.evaluated_designs.Profile==b.Profile & ...
        s.evaluated_designs.Family==b.Family & s.evaluated_designs.PassesScreen,:);
    selectionError=b.MTOW_lb-min(candidates.MTOW_lb);
    root=2*a.SW/(a.span*(1+a.msn.TR)); cg=a.cruise_geometry;
    row=struct('Profile',b.Profile,'Family',b.Family,'MTOW_lb',a.MTOW, ...
        'WS_lb_ft2',a.WSR,'AR_extended',a.msn.AR,'Taper',a.msn.TR, ...
        'AreaExtended_ft2',a.SW,'SpanExtended_ft',a.span, ...
        'RootChord_ft',root,'TipChord_ft',root*a.msn.TR,'MAC_ft',a.MAC, ...
        'ThicknessChord',a.msn.TCA,'CoreSpan_ft',cg.retracted_span, ...
        'MinimumSpan_ft',cg.retracted_span,'StrokeEach_ft',cg.stroke_each_ft, ...
        'CruiseSpan_ft',cg.span,'CruiseArea_ft2',cg.area,'CruiseAR',cg.AR, ...
        'CruiseDeployment',cg.deployment, ...
        'RetractionCapability_percent',100*a.options.retract_fraction, ...
        'ActualCruiseRetraction_percent',100*cg.actual_retraction_fraction, ...
        'CruiseHubEachSide_ft',a.prop_layout.y_side(end), ...
        'WingStructure_lb',a.W.wing,'Mechanism_lb',a.W.telescoping, ...
        'Landing_ft',a.con.S_land_ft,'BoundaryVariables',b.BoundaryVariables);
    if isempty(geometry), geometry=row; else, geometry(end+1,1)=row; end %#ok<AGROW>
    w=a.W;
    mass=struct('Profile',b.Profile,'Family',b.Family,'WingStructure_lb',w.wing, ...
        'Mechanism_lb',w.telescoping,'Tails_lb',w.htail+w.vtail,'Fuselage_lb',w.fuse, ...
        'LandingGear_lb',w.gear,'Motors_lb',w.motor,'Inverters_lb',w.power_elec, ...
        'Thermal_lb',w.thermal,'Propellers_lb',w.propeller,'Installation_lb',w.install, ...
        'ReverseHardware_lb',w.reverse_hardware,'Controls_lb',w.controls, ...
        'Avionics_lb',w.avionics,'Electrical_lb',w.electrical,'Furnishings_lb',w.furnishings, ...
        'Margin_lb',w.margin,'Battery_lb',w.battery,'Payload_lb',a.msn.payload);
    values=struct2cell(mass); mass.Total_lb=sum(cell2mat(values(3:end)));
    mass.MTOW_lb=a.MTOW;
    if isempty(masses), masses=mass; else, masses(end+1,1)=mass; end %#ok<AGROW>
    check=struct('Profile',b.Profile,'Family',b.Family, ...
        'SelectedMinimumResidual_lb',selectionError, ...
        'ReturnedMTOWResidual_lb',a.MTOW-b.MTOW_lb, ...
        'MassClosureResidual_lb',mass.Total_lb-a.MTOW, ...
        'AreaResidual_ft2',a.SW-a.MTOW/a.WSR, ...
        'SpanResidual_ft',a.span-sqrt(a.msn.AR*a.SW), ...
        'TaperResidual',a.msn.TR-b.Taper, ...
        'LandingPass',a.con.landing_ok || ~a.msn.enforce_land, ...
        'PhaseSchedulePass',b.PhaseSchedulePass,'Passes',true);
    assert(abs(selectionError)<1e-8 && abs(check.ReturnedMTOWResidual_lb)<1e-8, ...
        'AEGAoptimizewings2035:selection','Returned aircraft is not the selected sampled optimum.');
    assert(abs(check.MassClosureResidual_lb)<=a.options.weight_tolerance+1e-8 && ...
        abs(check.AreaResidual_ft2)<1e-8 && abs(check.SpanResidual_ft)<1e-8 && ...
        abs(check.TaperResidual)<1e-8 && check.LandingPass && check.PhaseSchedulePass, ...
        'AEGAoptimizewings2035:geometry','Selected aircraft geometry, mass or constraints do not match.');
    if b.Family=="Fixed"
        assert(a.options.retract_fraction==0 && w.telescoping==0 && abs(cg.span-a.span)<1e-8);
    else
        assert(a.msn.AR==s.options.extended_AR && w.telescoping>0 && ...
            abs(a.prop_layout.y_side(end)-cg.retracted_span/2)<1e-8);
    end
    if isempty(checks), checks=check; else, checks(end+1,1)=check; end %#ok<AGROW>
end
s.optimized_wings=struct2table(geometry);
s.selected_mass_breakdown=struct2table(masses);
s.optimization_checks=struct2table(checks);
% Convenient default-mission aliases; multi-profile results remain explicit.
s.fixed=s.optimized_aircraft(1).fixed;
s.adaptive=s.optimized_aircraft(1).adaptive;
if ~isempty(s.options.output_dir)
    if ~isfolder(s.options.output_dir), mkdir(s.options.output_dir); end
    writetable(s.optimized_wings,fullfile(s.options.output_dir,'09_optimized_wing_geometry.csv'));
    writetable(s.selected_mass_breakdown,fullfile(s.options.output_dir,'10_selected_mass_breakdown.csv'));
    writetable(s.optimization_checks,fullfile(s.options.output_dir,'11_optimization_checks.csv'));
end
end
